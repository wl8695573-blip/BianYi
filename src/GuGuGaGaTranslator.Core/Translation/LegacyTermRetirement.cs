    public static bool IsUnchangedLegacy(GameTerm term)
    {
        if (!string.IsNullOrWhiteSpace(term.ReviewStatus) && term.ReviewStatus is not ("历史收录" or "待核对"))
            return false;
        var text = string.Join('\u001f', GameProfiles.LanguageOf(term.Language) ?? "any", term.Source.Trim(),
            term.Target, term.Enabled ? "1" : "0", string.Join('\u001e', term.Forbidden), term.Note ?? "", term.SourceUrl ?? "");
        return Fingerprints.Contains(Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text))).ToLowerInvariant());
    }

    public static GameProfile PrepareLocal(GameProfile local, GameProfile incoming)
    {
        var result = GameProfileArchive.Clone(local);
        if (incoming.Id != "limbus-company" || !Version.TryParse(incoming.ProfileVersion, out var next)
            || next < Version.Parse(IndependentVersion)) return result;
        static string Key(GameTerm term) => (GameProfiles.LanguageOf(term.Language) ?? "any") + "|" + term.Source.Trim();
        var replacements = GameProfileArchive.Clone(incoming).Terms.ToDictionary(Key, StringComparer.OrdinalIgnoreCase);
        result.Terms = result.Terms.Select(term => IsUnchangedLegacy(term)
            ? replacements.GetValueOrDefault(Key(term)) : term).Where(term => term is not null).Cast<GameTerm>().ToList();
        return result;
    }
